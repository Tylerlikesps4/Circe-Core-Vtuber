import { existsSync } from "node:fs";
import { runProcess, ProcResult } from "./proc.js";

/**
 * Build the platform command that plays `file` through the host's speakers.
 * Windows uses a blocking PowerShell MediaPlayer session, macOS uses `afplay`,
 * Linux prefers `paplay` (PulseAudio/PipeWire).
 */
export function playbackCommand(
  platform: NodeJS.Platform,
  file: string,
): { cmd: string; args: string[] } {
  if (platform === "win32") {
    const escaped = JSON.stringify(file);
    const script = [
      "Add-Type -AssemblyName PresentationCore",
      `$uri = New-Object System.Uri(${escaped})`,
      "$p = New-Object System.Windows.Media.MediaPlayer",
      "$p.Open($uri)",
      "$p.Play()",
      "while ($p.Position -lt $p.NaturalDuration.TimeSpan) { Start-Sleep -Milliseconds 200 }",
      "$p.Close()",
    ].join("; ");
    return { cmd: "powershell", args: ["-NoProfile", "-NonInteractive", "-Command", script] };
  }
  if (platform === "darwin") {
    return { cmd: "afplay", args: [file] };
  }
  return { cmd: "paplay", args: [file] };
}

const LINUX_FALLBACKS: { cmd: string; args: string[] }[] = [
  { cmd: "aplay", args: [] },
  { cmd: "ffplay", args: ["-nodisp", "-autoexit", "-loglevel", "quiet"] },
];

/**
 * Play an audio file (wav/mp3) generated by a TTS backend. Resolves once
 * playback finishes so replies stay sequential during a stream.
 */
export async function playAudioFile(
  file: string,
  platform: NodeJS.Platform = process.platform,
): Promise<ProcResult> {
  if (!existsSync(file)) {
    return { ok: false, detail: `file not found: ${file}` };
  }
  const command = playbackCommand(platform, file);
  const result = await runProcess(command.cmd, command.args);
  if (platform === "linux" && !result.ok && result.detail?.includes("ENOENT")) {
    for (const fallback of LINUX_FALLBACKS) {
      const attempt = await runProcess(fallback.cmd, [...fallback.args, file]);
      if (attempt.ok || !attempt.detail?.includes("ENOENT")) return attempt;
    }
  }
  return result;
}
